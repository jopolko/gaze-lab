"""Copies the game's picture looks (the psylook shader and the look names) out of index.html into psylook.js, so other pages (the title screen)
show exactly the game's own effects. Run after changing a look in index.html:  python tools/make_psylook.py"""
import re, os, json
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
s = open(os.path.join(HERE, 'index.html'), encoding='utf-8').read()
m = re.search(r"ShadersStore\['psylookFragmentShader'\] = `(.*?)`;", s, re.S)
assert m, 'psylook shader not found'
fs = m.group(1)
assert '${' not in fs and '`' not in fs
names = re.search(r"const LOOKNAMES = (\[[^\]]*\])", s).group(1)
names = json.loads(names.replace("'", '"'))
out = ('// GENERATED by tools/make_psylook.py from index.html: the game\'s picture looks. Do not edit here; edit index.html and run the tool.\n'
       '// LOOKNAMES[i]: 1 = vector (uVec), 2 = ascii (uAsc), 3 and up = a style (uSty = strength, uMix = i - 2).\n'
       'export const LOOKNAMES = ' + json.dumps(names) + ';\n'
       'export const PSYLOOK_FS = `' + fs + '`;\n')
open(os.path.join(HERE, 'psylook.js'), 'w', encoding='utf-8', newline='\n').write(out)
print('psylook.js', len(out), 'bytes,', len(names), 'looks')
